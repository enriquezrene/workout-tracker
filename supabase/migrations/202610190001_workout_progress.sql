create table if not exists public.workout_sessions (
  id text primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  workout_date date not null,
  routine_id text not null,
  routine_name text not null,
  focus text not null,
  completed_sets integer not null default 0 check (completed_sets >= 0),
  total_sets integer not null default 0 check (total_sets >= 0),
  total_volume numeric not null default 0 check (total_volume >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.exercise_entries (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  session_id text not null references public.workout_sessions (id) on delete cascade,
  exercise_id text not null,
  exercise_name text not null,
  prescription text not null,
  default_sets integer not null check (default_sets >= 0),
  suggested text,
  optional boolean not null default false,
  unit text not null default 'reps' check (unit in ('reps', 'sec')),
  notes text not null default '',
  position integer not null check (position > 0),
  unique (session_id, position)
);

create table if not exists public.exercise_sets (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  exercise_entry_id bigint not null references public.exercise_entries (id) on delete cascade,
  set_number integer not null check (set_number > 0),
  reps numeric check (reps >= 0),
  kg numeric check (kg >= 0),
  reps_in_reserve numeric check (reps_in_reserve between 0 and 10),
  fatigue_rer numeric check (fatigue_rer between 0 and 10),
  completed boolean not null default false,
  unique (exercise_entry_id, set_number)
);

create index if not exists workout_sessions_owner_date_idx
  on public.workout_sessions (owner_id, workout_date desc, created_at desc);
create index if not exists exercise_entries_session_idx
  on public.exercise_entries (session_id, position);
create index if not exists exercise_sets_entry_idx
  on public.exercise_sets (exercise_entry_id, set_number);

alter table public.workout_sessions enable row level security;
alter table public.exercise_entries enable row level security;
alter table public.exercise_sets enable row level security;

create policy "Users manage their workout sessions"
  on public.workout_sessions
  for all
  to authenticated
  using (owner_id = auth.uid())
  with check (owner_id = auth.uid());

create policy "Users manage their exercise entries"
  on public.exercise_entries
  for all
  to authenticated
  using (owner_id = auth.uid())
  with check (owner_id = auth.uid());

create policy "Users manage their exercise sets"
  on public.exercise_sets
  for all
  to authenticated
  using (owner_id = auth.uid())
  with check (owner_id = auth.uid());

create or replace function public.save_workout_session(p_workout jsonb)
returns text
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_owner_id uuid := auth.uid();
  v_session_id text := p_workout ->> 'id';
  v_exercise jsonb;
  v_exercise_position bigint;
  v_exercise_entry_id bigint;
  v_set jsonb;
  v_set_number bigint;
begin
  if v_owner_id is null then
    raise exception 'Authentication is required';
  end if;

  if coalesce(v_session_id, '') = '' then
    raise exception 'Workout session id is required';
  end if;

  delete from public.workout_sessions
  where id = v_session_id and owner_id = v_owner_id;

  insert into public.workout_sessions (
    id,
    owner_id,
    workout_date,
    routine_id,
    routine_name,
    focus,
    completed_sets,
    total_sets,
    total_volume
  )
  values (
    v_session_id,
    v_owner_id,
    (p_workout ->> 'date')::date,
    p_workout ->> 'routineId',
    p_workout ->> 'routineName',
    p_workout ->> 'focus',
    coalesce((p_workout ->> 'completedSets')::integer, 0),
    coalesce((p_workout ->> 'totalSets')::integer, 0),
    coalesce((p_workout ->> 'totalVolume')::numeric, 0)
  );

  for v_exercise, v_exercise_position in
    select value, ordinality
    from jsonb_array_elements(coalesce(p_workout -> 'exercises', '[]'::jsonb)) with ordinality
  loop
    insert into public.exercise_entries (
      owner_id,
      session_id,
      exercise_id,
      exercise_name,
      prescription,
      default_sets,
      suggested,
      optional,
      unit,
      notes,
      position
    )
    values (
      v_owner_id,
      v_session_id,
      v_exercise ->> 'id',
      v_exercise ->> 'name',
      v_exercise ->> 'prescription',
      coalesce((v_exercise ->> 'defaultSets')::integer, 0),
      nullif(v_exercise ->> 'suggested', ''),
      coalesce((v_exercise ->> 'optional')::boolean, false),
      coalesce(nullif(v_exercise ->> 'unit', ''), 'reps'),
      coalesce(v_exercise ->> 'notes', ''),
      v_exercise_position
    )
    returning id into v_exercise_entry_id;

    for v_set, v_set_number in
      select value, ordinality
      from jsonb_array_elements(coalesce(v_exercise -> 'sets', '[]'::jsonb)) with ordinality
    loop
      insert into public.exercise_sets (
        owner_id,
        exercise_entry_id,
        set_number,
        reps,
        kg,
        reps_in_reserve,
        fatigue_rer,
        completed
      )
      values (
        v_owner_id,
        v_exercise_entry_id,
        v_set_number,
        nullif(v_set ->> 'reps', '')::numeric,
        nullif(v_set ->> 'weight', '')::numeric,
        nullif(v_set ->> 'repsInReserve', '')::numeric,
        nullif(v_set ->> 'fatigueRer', '')::numeric,
        coalesce((v_set ->> 'done')::boolean, false)
      );
    end loop;
  end loop;

  return v_session_id;
end;
$$;

create or replace view public.exercise_progress
with (security_invoker = true)
as
select
  sessions.workout_date as date,
  case
    when lower(sessions.focus) like 'upper%' then 'upper'
    when lower(sessions.focus) like 'lower%' then 'lower'
    else lower(sessions.focus)
  end as "group",
  entries.exercise_name as exercise,
  sets.set_number,
  sets.reps,
  sets.kg,
  sets.reps_in_reserve,
  sets.fatigue_rer,
  entries.notes,
  sets.completed
from public.workout_sessions as sessions
join public.exercise_entries as entries on entries.session_id = sessions.id
join public.exercise_sets as sets on sets.exercise_entry_id = entries.id;

grant select on public.workout_sessions, public.exercise_entries, public.exercise_sets to authenticated;
grant insert, update, delete on public.workout_sessions, public.exercise_entries, public.exercise_sets to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant select on public.exercise_progress to authenticated;
grant execute on function public.save_workout_session(jsonb) to authenticated;
